package net.exylia.lib.redis.internal;

import com.google.gson.Gson;
import com.google.gson.reflect.TypeToken;
import net.exylia.lib.database.internal.SqlBackend;
import net.exylia.lib.database.internal.SqlSettings;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.lang.reflect.Type;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.AbstractMap;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.ConcurrentHashMap;

/**
 * The database bus on MySQL, MariaDB or PostgreSQL (and H2, for tests).
 *
 * <p>Six small tables, created on first use and shared by every plugin and
 * every network on the database: channel names and keys already carry the
 * network's {@code key-prefix}.
 *
 * <h2>Streams keep Redis's promise</h2>
 * A consumer group hands each entry to one consumer, once, until it is
 * acknowledged or claimed. Appends and group reads on a stream both lock that
 * stream's row first, so a reader can never move its group past an entry
 * whose append has not committed yet.
 *
 * <p>Postgres is woken by {@code NOTIFY} as soon as a message is stored, so its
 * latency is the round trip, not the poll interval.
 */
final class SqlBus extends DatabaseBus {

    static final String MESSAGES = "exylia_bus_messages";
    static final String KEYS = "exylia_bus_keys";
    static final String STREAMS = "exylia_bus_streams";
    static final String ENTRIES = "exylia_bus_entries";
    static final String GROUPS = "exylia_bus_groups";
    static final String PENDING = "exylia_bus_pending";

    /** The Postgres notification channel publishes wake readers on. */
    static final String NOTIFY_CHANNEL = "exylia_bus";

    private static final Gson GSON = new Gson();
    private static final Type FIELDS = new TypeToken<Map<String, String>>() { }.getType();

    private final SqlBackend backend;
    private final Engine engine;
    private final Set<String> knownStreams = ConcurrentHashMap.newKeySet();
    private final @Nullable PostgresWake wake;

    /** What changes between engines: types, upserts and wake-ups. */
    enum Engine { MYSQL, POSTGRES, H2 }

    private SqlBus(SqlBackend backend, Engine engine, String name) {
        super(name);
        this.backend = backend;
        this.engine = engine;
        this.wake = engine == Engine.POSTGRES ? new PostgresWake(backend, NOTIFY_CHANNEL) : null;
    }

    static @NotNull SqlBus connect(@NotNull SqlSettings settings, @NotNull String name) {
        // A pool of its own, small: the poller, a publisher or two, and the
        // Postgres listener. Sharing the plugin's pool would let a burst of
        // saves starve the poll, and its lifetime ends with the plugin.
        SqlBackend backend = SqlBackend.open(settings.poolSize(4), name + "-bus");
        Engine engine = switch (backend.dialect().id()) {
            case "postgres" -> Engine.POSTGRES;
            case "h2" -> Engine.H2;
            default -> Engine.MYSQL;
        };
        SqlBus bus = new SqlBus(backend, engine, name);
        try {
            try {
                bus.createTables();
            } catch (SQLException raced) {
                // Two servers starting together both see "not exists" and one
                // of the creates fails (Postgres and H2 both do this). Once the
                // other has finished, every statement is a no-op.
                Thread.sleep(250);
                bus.createTables();
            }
        } catch (InterruptedException interrupted) {
            Thread.currentThread().interrupt();
            bus.closeStore();
            throw new IllegalStateException("Interrupted while creating the cross-server tables", interrupted);
        } catch (SQLException failure) {
            bus.closeStore();
            throw new IllegalStateException("Could not create the cross-server tables: " + failure.getMessage(),
                    failure);
        }
        return bus;
    }

    // ------------------------------------------------------------------- schema

    private void createTables() throws SQLException {
        boolean mysql = engine == Engine.MYSQL;
        String serial = mysql ? "BIGINT NOT NULL AUTO_INCREMENT" : "BIGINT GENERATED BY DEFAULT AS IDENTITY";
        String text = mysql ? "MEDIUMTEXT" : "TEXT";
        List<String> ddl = new ArrayList<>();
        ddl.add("CREATE TABLE IF NOT EXISTS " + MESSAGES + " (id " + serial + " PRIMARY KEY,"
                + " channel VARCHAR(255) NOT NULL, payload " + text + " NOT NULL, created BIGINT NOT NULL)");
        ddl.add("CREATE TABLE IF NOT EXISTS " + KEYS + " (k VARCHAR(512) NOT NULL PRIMARY KEY,"
                + " v " + text + " NOT NULL, expires BIGINT NOT NULL)");
        ddl.add("CREATE TABLE IF NOT EXISTS " + STREAMS + " (stream VARCHAR(255) NOT NULL PRIMARY KEY)");
        ddl.add("CREATE TABLE IF NOT EXISTS " + ENTRIES + " (id " + serial + " PRIMARY KEY,"
                + " stream VARCHAR(255) NOT NULL, fields " + text + " NOT NULL)");
        ddl.add("CREATE TABLE IF NOT EXISTS " + GROUPS + " (stream VARCHAR(255) NOT NULL,"
                + " grp VARCHAR(255) NOT NULL, last_id BIGINT NOT NULL, PRIMARY KEY (stream, grp))");
        ddl.add("CREATE TABLE IF NOT EXISTS " + PENDING + " (stream VARCHAR(255) NOT NULL,"
                + " grp VARCHAR(255) NOT NULL, id BIGINT NOT NULL, consumer VARCHAR(255) NOT NULL,"
                + " delivered BIGINT NOT NULL, deliveries INT NOT NULL, PRIMARY KEY (stream, grp, id))");
        try (Connection connection = backend.connection(); Statement statement = connection.createStatement()) {
            for (String sql : ddl) {
                statement.execute(sql);
            }
            index(statement, MESSAGES + "_created", MESSAGES, "created");
            index(statement, KEYS + "_expires", KEYS, "expires");
            index(statement, ENTRIES + "_stream", ENTRIES, "stream, id");
        }
    }

    /** MySQL has no {@code CREATE INDEX IF NOT EXISTS}, so a duplicate is the sign it is there. */
    private void index(Statement statement, String name, String table, String columns) throws SQLException {
        if (engine != Engine.MYSQL) {
            statement.execute("CREATE INDEX IF NOT EXISTS " + name + " ON " + table + " (" + columns + ")");
            return;
        }
        try {
            statement.execute("CREATE INDEX " + name + " ON " + table + " (" + columns + ")");
        } catch (SQLException exists) {
            // 1061: duplicate key name.
            if (exists.getErrorCode() != 1061) {
                throw exists;
            }
        }
    }

    // ----------------------------------------------------------------- messages

    @Override
    protected long newestId() throws SQLException {
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("SELECT MAX(id) FROM " + MESSAGES);
             ResultSet rows = statement.executeQuery()) {
            return rows.next() ? rows.getLong(1) : 0L;
        }
    }

    @Override
    protected @NotNull List<Envelope> readAfter(long after, int limit) throws SQLException {
        List<Envelope> found = new ArrayList<>();
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("SELECT id, channel, payload FROM "
                     + MESSAGES + " WHERE id > ? ORDER BY id LIMIT ?")) {
            statement.setLong(1, after);
            statement.setInt(2, limit);
            try (ResultSet rows = statement.executeQuery()) {
                while (rows.next()) {
                    found.add(new Envelope(rows.getLong(1), rows.getString(2), rows.getString(3)));
                }
            }
        }
        return found;
    }

    @Override
    protected void insert(@NotNull String channel, @NotNull String message, long now) throws SQLException {
        try (Connection connection = backend.connection()) {
            try (PreparedStatement statement = connection.prepareStatement("INSERT INTO " + MESSAGES
                    + " (channel, payload, created) VALUES (?, ?, ?)")) {
                statement.setString(1, channel);
                statement.setString(2, message);
                statement.setLong(3, now);
                statement.executeUpdate();
            }
            if (engine == Engine.POSTGRES) {
                try (Statement statement = connection.createStatement()) {
                    statement.execute("NOTIFY " + NOTIFY_CHANNEL);
                }
            }
        }
    }

    @Override
    protected void purge(long before, long now) throws SQLException {
        try (Connection connection = backend.connection()) {
            try (PreparedStatement statement = connection.prepareStatement("DELETE FROM " + MESSAGES
                    + " WHERE created < ?")) {
                statement.setLong(1, before);
                statement.executeUpdate();
            }
            try (PreparedStatement statement = connection.prepareStatement("DELETE FROM " + KEYS
                    + " WHERE expires > 0 AND expires <= ?")) {
                statement.setLong(1, now);
                statement.executeUpdate();
            }
        }
    }

    @Override
    protected void await(long millis) throws InterruptedException {
        if (wake == null || !wake.await(millis)) {
            Thread.sleep(millis);
        }
    }

    @Override
    protected void closeStore() {
        if (wake != null) {
            wake.close();
        }
        backend.close();
    }

    // --------------------------------------------------------------------- keys

    @Override
    public @Nullable String get(@NotNull String key) {
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("SELECT v, expires FROM " + KEYS
                     + " WHERE k = ?")) {
            statement.setString(1, key);
            try (ResultSet rows = statement.executeQuery()) {
                if (!rows.next()) {
                    return null;
                }
                long expires = rows.getLong(2);
                return expires > 0 && expires <= System.currentTimeMillis() ? null : rows.getString(1);
            }
        } catch (SQLException failure) {
            throw failed("read " + key, failure);
        }
    }

    @Override
    public void set(@NotNull String key, @NotNull String value, int ttlSeconds) {
        setUntil(key, value, System.currentTimeMillis() + Math.max(1, ttlSeconds) * 1_000L);
    }

    @Override
    public void setUntil(@NotNull String key, @NotNull String value, long expireAtMillis) {
        String sql = switch (engine) {
            case MYSQL -> "INSERT INTO " + KEYS + " (k, v, expires) VALUES (?, ?, ?)"
                    + " ON DUPLICATE KEY UPDATE v = ?, expires = ?";
            case POSTGRES -> "INSERT INTO " + KEYS + " (k, v, expires) VALUES (?, ?, ?)"
                    + " ON CONFLICT (k) DO UPDATE SET v = EXCLUDED.v, expires = EXCLUDED.expires";
            case H2 -> "MERGE INTO " + KEYS + " (k, v, expires) KEY (k) VALUES (?, ?, ?)";
        };
        long expires = Math.max(0, expireAtMillis);
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, key);
            statement.setString(2, value);
            statement.setLong(3, expires);
            if (engine == Engine.MYSQL) {
                statement.setString(4, value);
                statement.setLong(5, expires);
            }
            statement.executeUpdate();
        } catch (SQLException failure) {
            throw failed("write " + key, failure);
        }
    }

    @Override
    public boolean setIfAbsent(@NotNull String key, @NotNull String value, long ttlMillis) {
        long now = System.currentTimeMillis();
        try (Connection connection = backend.connection()) {
            // An expired holder is gone in Redis, so it is gone here first.
            // The condition keeps a fresh holder another server just wrote.
            try (PreparedStatement statement = connection.prepareStatement("DELETE FROM " + KEYS
                    + " WHERE k = ? AND expires > 0 AND expires <= ?")) {
                statement.setString(1, key);
                statement.setLong(2, now);
                statement.executeUpdate();
            }
            try (PreparedStatement statement = connection.prepareStatement("INSERT INTO " + KEYS
                    + " (k, v, expires) VALUES (?, ?, ?)")) {
                statement.setString(1, key);
                statement.setString(2, value);
                statement.setLong(3, now + Math.max(1, ttlMillis));
                statement.executeUpdate();
                return true;
            } catch (SQLException taken) {
                if (SqlBackend.duplicateKey(taken)) {
                    return false;
                }
                throw taken;
            }
        } catch (SQLException failure) {
            throw failed("lock " + key, failure);
        }
    }

    @Override
    public void delete(@NotNull Collection<String> keys) {
        if (keys.isEmpty()) {
            return;
        }
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("DELETE FROM " + KEYS + " WHERE k = ?")) {
            for (String key : keys) {
                statement.setString(1, key);
                statement.addBatch();
            }
            statement.executeBatch();
        } catch (SQLException failure) {
            throw failed("delete keys", failure);
        }
    }

    @Override
    public void deleteByPrefix(@NotNull String prefix) {
        // '!' rather than a backslash: the one escape character every engine
        // reads the same way, whatever its string-literal settings.
        String pattern = prefix.replace("!", "!!").replace("%", "!%").replace("_", "!_") + '%';
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("DELETE FROM " + KEYS
                     + " WHERE k LIKE ? ESCAPE '!'")) {
            statement.setString(1, pattern);
            statement.executeUpdate();
        } catch (SQLException failure) {
            throw failed("delete " + prefix + "*", failure);
        }
    }

    // ------------------------------------------------------------------ streams

    @Override
    public @NotNull String streamAdd(@NotNull String stream, @NotNull Map<String, String> fields, long maxLength) {
        try {
            ensureStream(stream);
            try (Connection connection = backend.connection()) {
                connection.setAutoCommit(false);
                try {
                    lockStream(connection, stream);
                    long id;
                    try (PreparedStatement statement = connection.prepareStatement("INSERT INTO " + ENTRIES
                            + " (stream, fields) VALUES (?, ?)", new String[]{"id"})) {
                        statement.setString(1, stream);
                        statement.setString(2, GSON.toJson(fields));
                        statement.executeUpdate();
                        try (ResultSet keys = statement.getGeneratedKeys()) {
                            keys.next();
                            id = keys.getLong(1);
                        }
                    }
                    if (maxLength > 0) {
                        // About maxLength, like Redis's ~ trim: numbers are shared
                        // between streams, so this keeps at least that many.
                        try (PreparedStatement statement = connection.prepareStatement("DELETE FROM " + ENTRIES
                                + " WHERE stream = ? AND id <= ?")) {
                            statement.setString(1, stream);
                            statement.setLong(2, id - maxLength);
                            statement.executeUpdate();
                        }
                    }
                    connection.commit();
                    return Long.toString(id);
                } catch (SQLException | RuntimeException failure) {
                    connection.rollback();
                    throw failure;
                } finally {
                    connection.setAutoCommit(true);
                }
            }
        } catch (SQLException failure) {
            throw failed("append to " + stream, failure);
        }
    }

    @Override
    public void streamGroup(@NotNull String stream, @NotNull String group) {
        try {
            ensureStream(stream);
            try (Connection connection = backend.connection();
                 PreparedStatement statement = connection.prepareStatement("INSERT INTO " + GROUPS
                         + " (stream, grp, last_id) VALUES (?, ?, 0)")) {
                statement.setString(1, stream);
                statement.setString(2, group);
                statement.executeUpdate();
            } catch (SQLException exists) {
                if (!SqlBackend.duplicateKey(exists)) {
                    throw exists;
                }
            }
        } catch (SQLException failure) {
            throw failed("create group " + group + " on " + stream, failure);
        }
    }

    @Override
    public @NotNull List<Map.Entry<String, Map<String, String>>> streamRead(@NotNull String stream,
                                                                          @NotNull String group,
                                                                          @NotNull String consumer, int count) {
        try (Connection connection = backend.connection()) {
            connection.setAutoCommit(false);
            try {
                lockStream(connection, stream);
                long last;
                try (PreparedStatement statement = connection.prepareStatement("SELECT last_id FROM " + GROUPS
                        + " WHERE stream = ? AND grp = ? FOR UPDATE")) {
                    statement.setString(1, stream);
                    statement.setString(2, group);
                    try (ResultSet rows = statement.executeQuery()) {
                        if (!rows.next()) {
                            throw new IllegalStateException("NOGROUP No such consumer group '" + group
                                    + "' for stream '" + stream + "'");
                        }
                        last = rows.getLong(1);
                    }
                }
                List<Map.Entry<String, Map<String, String>>> entries = new ArrayList<>();
                List<Long> ids = new ArrayList<>();
                try (PreparedStatement statement = connection.prepareStatement("SELECT id, fields FROM " + ENTRIES
                        + " WHERE stream = ? AND id > ? ORDER BY id LIMIT ?")) {
                    statement.setString(1, stream);
                    statement.setLong(2, last);
                    statement.setInt(3, Math.max(1, count));
                    try (ResultSet rows = statement.executeQuery()) {
                        while (rows.next()) {
                            ids.add(rows.getLong(1));
                            entries.add(pair(rows.getLong(1), rows.getString(2)));
                        }
                    }
                }
                if (!ids.isEmpty()) {
                    try (PreparedStatement statement = connection.prepareStatement("UPDATE " + GROUPS
                            + " SET last_id = ? WHERE stream = ? AND grp = ?")) {
                        statement.setLong(1, ids.get(ids.size() - 1));
                        statement.setString(2, stream);
                        statement.setString(3, group);
                        statement.executeUpdate();
                    }
                    long now = System.currentTimeMillis();
                    try (PreparedStatement statement = connection.prepareStatement("INSERT INTO " + PENDING
                            + " (stream, grp, id, consumer, delivered, deliveries) VALUES (?, ?, ?, ?, ?, 1)")) {
                        for (long id : ids) {
                            statement.setString(1, stream);
                            statement.setString(2, group);
                            statement.setLong(3, id);
                            statement.setString(4, consumer);
                            statement.setLong(5, now);
                            statement.addBatch();
                        }
                        statement.executeBatch();
                    }
                }
                connection.commit();
                return entries;
            } catch (SQLException | RuntimeException failure) {
                connection.rollback();
                throw failure;
            } finally {
                connection.setAutoCommit(true);
            }
        } catch (SQLException failure) {
            throw failed("read " + stream, failure);
        }
    }

    @Override
    public @NotNull List<Map.Entry<String, Long>> streamPending(@NotNull String stream, @NotNull String group,
                                                                long minIdleMillis, int count) {
        List<Map.Entry<String, Long>> pending = new ArrayList<>();
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("SELECT id, deliveries FROM " + PENDING
                     + " WHERE stream = ? AND grp = ? AND delivered <= ? ORDER BY id LIMIT ?")) {
            statement.setString(1, stream);
            statement.setString(2, group);
            statement.setLong(3, System.currentTimeMillis() - Math.max(0, minIdleMillis));
            statement.setInt(4, Math.max(1, count));
            try (ResultSet rows = statement.executeQuery()) {
                while (rows.next()) {
                    pending.add(new AbstractMap.SimpleImmutableEntry<>(Long.toString(rows.getLong(1)),
                            rows.getLong(2)));
                }
            }
            return pending;
        } catch (SQLException failure) {
            throw failed("list pending on " + stream, failure);
        }
    }

    @Override
    public @NotNull List<Map.Entry<String, Map<String, String>>> streamClaim(@NotNull String stream,
                                                                           @NotNull String group,
                                                                           @NotNull String consumer,
                                                                           long minIdleMillis,
                                                                           @NotNull Collection<String> ids) {
        if (ids.isEmpty()) {
            return List.of();
        }
        List<Map.Entry<String, Map<String, String>>> claimed = new ArrayList<>();
        long now = System.currentTimeMillis();
        try (Connection connection = backend.connection();
             PreparedStatement take = connection.prepareStatement("UPDATE " + PENDING
                     + " SET consumer = ?, delivered = ?, deliveries = deliveries + 1"
                     + " WHERE stream = ? AND grp = ? AND id = ? AND delivered <= ?");
             PreparedStatement read = connection.prepareStatement("SELECT fields FROM " + ENTRIES
                     + " WHERE id = ? AND stream = ?");
             PreparedStatement forget = connection.prepareStatement("DELETE FROM " + PENDING
                     + " WHERE stream = ? AND grp = ? AND id = ?")) {
            for (String raw : ids) {
                long id = entryId(raw);
                take.setString(1, consumer);
                take.setLong(2, now);
                take.setString(3, stream);
                take.setString(4, group);
                take.setLong(5, id);
                take.setLong(6, now - Math.max(0, minIdleMillis));
                if (take.executeUpdate() == 0) {
                    continue;
                }
                read.setLong(1, id);
                read.setString(2, stream);
                try (ResultSet rows = read.executeQuery()) {
                    if (rows.next()) {
                        claimed.add(pair(id, rows.getString(1)));
                        continue;
                    }
                }
                // Trimmed away: Redis drops such an entry from the pending list too.
                forget.setString(1, stream);
                forget.setString(2, group);
                forget.setLong(3, id);
                forget.executeUpdate();
            }
            return claimed;
        } catch (SQLException failure) {
            throw failed("claim on " + stream, failure);
        }
    }

    @Override
    public void streamAck(@NotNull String stream, @NotNull String group, @NotNull Collection<String> ids) {
        if (ids.isEmpty()) {
            return;
        }
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("DELETE FROM " + PENDING
                     + " WHERE stream = ? AND grp = ? AND id = ?")) {
            for (String id : ids) {
                statement.setString(1, stream);
                statement.setString(2, group);
                statement.setLong(3, entryId(id));
                statement.addBatch();
            }
            statement.executeBatch();
        } catch (SQLException failure) {
            throw failed("acknowledge on " + stream, failure);
        }
    }

    /** The row appends and group reads lock, created once, outside any transaction. */
    private void ensureStream(String stream) throws SQLException {
        if (knownStreams.contains(stream)) {
            return;
        }
        try (Connection connection = backend.connection();
             PreparedStatement statement = connection.prepareStatement("INSERT INTO " + STREAMS
                     + " (stream) VALUES (?)")) {
            statement.setString(1, stream);
            statement.executeUpdate();
        } catch (SQLException exists) {
            if (!SqlBackend.duplicateKey(exists)) {
                throw exists;
            }
        }
        knownStreams.add(stream);
    }

    private static void lockStream(Connection connection, String stream) throws SQLException {
        try (PreparedStatement statement = connection.prepareStatement("SELECT stream FROM " + STREAMS
                + " WHERE stream = ? FOR UPDATE")) {
            statement.setString(1, stream);
            statement.executeQuery().close();
        }
    }

    private static Map.Entry<String, Map<String, String>> pair(long id, String json) {
        Map<String, String> fields = json == null ? null : GSON.fromJson(json, FIELDS);
        return new AbstractMap.SimpleImmutableEntry<>(Long.toString(id), fields == null ? Map.of() : fields);
    }

    private static IllegalStateException failed(String what, SQLException failure) {
        return new IllegalStateException("Cross-server database could not " + what + ": " + failure.getMessage(),
                failure);
    }
}
