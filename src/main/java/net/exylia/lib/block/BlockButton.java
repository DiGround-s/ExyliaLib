package net.exylia.lib.block;

/**
 * Which mouse button clicked a registered block.
 *
 * @since 1.110.0
 */
public enum BlockButton {

    /** Left click: what a player does to break a block, so it never breaks one of these. */
    LEFT,

    /** Right click: what a player does to use a block, so it never opens one of these. */
    RIGHT
}
